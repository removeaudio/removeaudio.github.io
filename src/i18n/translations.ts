export function isValidLang(code: string | null | undefined): code is LangCode {
  return Boolean(code && Object.prototype.hasOwnProperty.call(TRANSLATIONS, code));
}

export function detectInitialLang(): LangCode {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem('removeaudio-lang');
    if (isValidLang(saved)) return saved;
  } catch {
    // Ignore storage errors
  }
  const navLang = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return isValidLang(navLang) ? navLang : 'en';
}
